def get_current_language() -> str:
    return SettingsManager().get_language()

def t(key: str, lang: str = None) -> str:
    cur_lang = lang or get_current_language()
    d = STRINGS.get(cur_lang, STRINGS["en"])
    if key in d:
        return d[key]
    return STRINGS["en"].get(key, key)
